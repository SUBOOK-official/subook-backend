// 운영 접속 없이 격리 PostgreSQL에서 새 DDL·RPC·권한·기존 신청 호환성을 검사한다.
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { PGlite } from '@electric-sql/pglite';

const db = new PGlite();
const read = (file) => readFileSync(new URL('../supabase/migrations/' + file, import.meta.url), 'utf8');
try {
  await db.exec(`
    create role anon; create role authenticated;
    create schema auth;
    create function auth.uid() returns uuid language sql as $$ select nullif(current_setting('test.uid', true), '')::uuid $$;
    create function public.is_admin_user() returns boolean language sql as $$ select coalesce(current_setting('test.admin', true) = 'true', false) $$;
    create table public.pickup_requests(id bigint generated by default as identity primary key, user_id uuid,
      status text default 'pending', box_count integer, tracking_number text, box_waybills jsonb default '[]', updated_at timestamptz default now());
    alter table public.pickup_requests enable row level security;
    create policy owner_read on public.pickup_requests for select to authenticated using(user_id = auth.uid());
    grant select on public.pickup_requests to authenticated;
    insert into public.pickup_requests(user_id,box_count) values ('00000000-0000-0000-0000-000000000001',2);
    -- 하위 신청 함수의 기존 검증은 유지, 새 래퍼의 인자 전달·원자적 저장만 이 fixture에서 검사.
    create function public.submit_pickup_request(text,text,text,text,text,text,text,text,text,jsonb,bigint,text,text,date,integer,integer,boolean)
    returns jsonb language plpgsql as $$ declare v_id bigint; begin
      if $17 is distinct from true then raise exception 'policy required'; end if;
      insert into public.pickup_requests(user_id,box_count) values(auth.uid(),$16) returning id into v_id;
      return jsonb_build_object('request_id',v_id,'account_id',$11,'desired_date',$14,'expected_count',$15);
    end $$;
    create function public.list_admin_pickup_requests(text,text[],date,date,integer,integer)
    returns table(id bigint,box_count integer) language sql as $$ select id,box_count from public.pickup_requests order by id desc limit $5 offset $6 $$;
    create function public.get_my_pickup_requests(integer,integer) returns jsonb language sql as $$
      select coalesce(jsonb_agg(to_jsonb(r) order by r.id desc),'[]') from (select id,box_count from public.pickup_requests where user_id=auth.uid() order by id desc limit $1 offset $2) r $$;
  `);
  // 실제 배포된 v2 소스: OTP/계좌 등을 가진 기존 함수를 재정의하지 않고 위임.
  const v2 = read('20260910054749_pickup_fee_policy_versions.sql').match(/create function public\.submit_pickup_request_v2\([\s\S]*?\$\$;/)[0];
  await db.exec(v2);
  await db.exec(read('20260918090800_pickup_box_type_selection.sql'));
  const scalar = async (sql, args = []) => (await db.query(sql, args)).rows[0];
  assert.equal((await scalar('select box_type_codes from pickup_requests where id=1')).box_type_codes, null);
  for (const [codes, count] of [[null,2],[[],0],[['01'],2],[['01',null],2],[['05'],1],[['06'],1],[['7'],1],[['07'],6]]) {
    assert.equal((await scalar('select valid_pickup_box_types($1,$2) ok', [codes,count])).ok, false);
  }
  assert.equal((await scalar("select valid_pickup_box_types(array['01','02','03','04','07'],5) ok")).ok,true);
  await assert.rejects(db.exec('insert into pickup_requests(box_count) values(1)'), /규격 선택이 필요/);
  const call = (codes, count = 2, policy = '2026-09', agreed = true) => scalar(`select submit_pickup_request_v3(
    'fixture','01000000000','00000','fixture','','','bank','123456','fixture','[]',$1,
    9,null,null,'2026-09-21',40,$2,$3,$4) result`, [codes,count,agreed,policy]);
  await assert.rejects(call(['03','07']), /로그인/);
  await db.exec("select set_config('test.uid','00000000-0000-0000-0000-000000000001',false)");
  await assert.rejects(call(['03']), /박스 수/);
  await assert.rejects(call(['03','07'],2,'old'), /약관/);
  await assert.rejects(call(['03','07'],2,'2026-09',false), /policy required/);
  const { result } = await call(['03','07']);
  assert.equal(result.account_id, 9); assert.equal(result.expected_count, 40); assert.equal(result.desired_date,'2026-09-21');
  assert.deepEqual((await scalar('select box_type_codes from pickup_requests where id=$1',[result.request_id])).box_type_codes,['03','07']);
  assert.equal((await scalar("select current_setting('subook.pickup_box_types',true) value")).value,'');
  await assert.rejects(db.exec('insert into pickup_requests(box_count) values(1)'), /규격 선택이 필요/);
  await assert.rejects(db.exec("update pickup_requests set box_type_codes=array['07'] where id=1"), /check constraint/);
  await assert.rejects(db.exec("select admin_set_pickup_box_types(1,array['03','07'])"), /Admin access/);
  await assert.rejects(db.exec('select list_admin_pickup_requests_v2()'), /Admin access/);
  await db.exec("select set_config('test.admin','true',false)");
  await db.exec("select admin_set_pickup_box_types(1,array['03','07'])");
  let rows = (await scalar('select list_admin_pickup_requests_v2() result')).result;
  assert.deepEqual(rows.map((r)=>r.id),[result.request_id,1]); assert.deepEqual(rows[1].box_type_codes,['03','07']);
  await db.exec(`update pickup_requests set box_waybills='[{"box_seq":1,"tracking_number":"111"}]' where id=1`);
  await assert.rejects(db.exec("select admin_set_pickup_box_types(1,array['02','02'])"), /CJ 재접수/);
  await db.exec(`update pickup_requests set box_waybills='[{"box_seq":1,"tracking_number":"111","cancelled_at":"2026-09-18"}]' where id=1`);
  await db.exec("select admin_set_pickup_box_types(1,array['02','02'])");
  await db.exec("update pickup_requests set status='arrived' where id=1");
  await assert.rejects(db.exec("select admin_set_pickup_box_types(1,array['03','03'])"), /현재 상태/);
  assert.equal((await scalar('select get_my_pickup_requests_v2() result')).result.length,2);
  await db.exec("select set_config('test.uid','00000000-0000-0000-0000-000000000002',false)");
  assert.deepEqual((await scalar('select get_my_pickup_requests_v2() result')).result,[]);
  await db.exec('set role authenticated');
  assert.equal((await db.query('select * from pickup_requests')).rows.length,0,'본인 이외 조회 불가');
  await assert.rejects(db.exec("update pickup_requests set box_type_codes=array['01','01']"), /permission denied/);
  await db.exec('reset role; set role anon');
  await assert.rejects(db.exec('select get_my_pickup_requests_v2()'), /permission denied/);
  await assert.rejects(call(['03','07']), /permission denied/);
  console.log('PASS: DB 규격 검증, 원자적 저장, 기존 신청 보존, 구형 신청서 차단, 목록 순서, 관리자 수정 가드, RLS·RPC 권한');
} finally { await db.close(); }
