import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import test from 'node:test';
import { PGlite } from '@electric-sql/pglite';

const read = name => readFileSync(new URL('../supabase/migrations/' + name, import.meta.url), 'utf8').replaceAll('\r\n', '\n');
const functionSql = (file, name) => {
  const match = read(file).match(new RegExp('create or replace function public\\.' + name + '\\([\\s\\S]*?AS (\\$[a-z_]*\\$)[\\s\\S]*?\\1\\s*;', 'i'));
  assert.ok(match, name);
  return match[0];
};
const listingMigration = '20260922180318_separate_product_listing_from_stock.sql';

test('등록 공개 의사·실제 결과·공개 버튼 조건을 실제 PostgreSQL에서 검증', async t => {
  const db = new PGlite();
  const register = async payload => (await db.query('select admin_register_customer_inventory(1,$1::jsonb) as result', [JSON.stringify(payload)])).rows[0].result;
  const existing = (id, isPublic = true, price = 10950, quantity = 1) => ({ existing_additions: [{ product_id: id, is_public: isPublic, options: [{ price, quantity }] }] });
  const product = async id => (await db.query('select is_listed,status from products where id=$1', [id])).rows[0];
  const visibility = async (id, value) => (await db.query('select admin_bulk_set_products_visibility(array[$1::bigint],$2) as result', [id, value])).rows[0].result;
  try {
    await db.exec(`
      create role anon; create role authenticated; create role service_role;
      create function is_admin_user() returns boolean language sql stable as $$select coalesce(current_setting('app.test_admin',true),'true')='true'$$;
      create function storefront_condition_grade_rank(text) returns integer language sql immutable as 'select 1';
      create function storefront_product_group_key(text,text,text,text,text,integer,text) returns text language sql immutable as 'select $1';
      create function _register_infer_product_meta(text) returns table(subject text,brand text,book_type text,year integer,instructor text)
        language sql as $$select '사회','마더텅','기출',2026,null::text$$;
      create function _register_resolve_book_type(jsonb) returns jsonb language sql as $$select '{"book_type":"기출","method":"manual"}'::jsonb$$;
      create sequence books_serial_number_seq start 5000;
      create function _next_book_serial() returns integer language sql as $$select nextval('books_serial_number_seq')::integer$$;
      create table shipments(id bigint primary key);
      insert into shipments values(1);
      create table products(id bigint generated by default as identity(start with 100) primary key,group_key text unique,title text,
        option text,subject text,brand text,book_type text,published_year integer,instructor_name text,cover_image_url text,
        status text default 'selling',is_listed boolean not null default true,updated_at timestamptz default now());
      create table books(id bigint generated always as identity primary key,shipment_id bigint references shipments(id),
        product_id bigint references products(id),title text,option text,subject text,brand text,book_type text,
        published_year integer,instructor_name text,original_price integer,price integer,condition_grade text,
        cover_image_url text,inspection_image_urls text[],status text,is_public boolean,discount_type text,discount_value integer,
        inspected_at timestamptz,serial_number integer unique,location text,writing_percentage integer,has_damage boolean,
        created_at timestamptz default now());
      create table product_type_reviews(product_id bigint,title text,book_type text,method text,evidence jsonb);
      insert into products(id,group_key,title,is_listed,status) values
        (1,'legacy','사회문화',false,'hidden'),(2,'private','비공개',false,'hidden'),
        (3,'missing-price','가격 없음',false,'hidden'),(4,'matched-new','matched-new',false,'hidden'),
        (5,'blocked','공개 제한',false,'hidden');
    `);
    for (const name of ['refresh_storefront_product_status', 'products_enforce_derived_status', 'books_enforce_public_storefront_rules', 'products_apply_listing_visibility', 'admin_bulk_set_products_visibility']) {
      await db.exec(functionSql(listingMigration, name));
    }
    await db.exec(functionSql('2026040709_z_add_products_storefront.sql', 'books_refresh_storefront_product_status'));
    await db.exec(functionSql('20260629120000_product_register_flow.sql', '_register_compute_price'));
    await db.exec(functionSql('20260930074813_book_type_classification_review.sql', 'admin_register_customer_inventory'));
    await db.exec(`
      create trigger books_guard before insert or update on books for each row execute function books_enforce_public_storefront_rules();
      create trigger books_refresh after insert or update or delete on books for each row execute function books_refresh_storefront_product_status();
      create trigger products_derive before insert or update of status,is_listed on products for each row execute function products_enforce_derived_status();
      create trigger products_hide after insert or update on products for each row when(not new.is_listed) execute function products_apply_listing_visibility();
      revoke all on function admin_register_customer_inventory(bigint,jsonb),admin_bulk_set_products_visibility(bigint[],boolean) from public,anon;
      grant execute on function admin_register_customer_inventory(bigint,jsonb),admin_bulk_set_products_visibility(bigint[],boolean) to authenticated,service_role;
    `);

    await t.test('수정 전: 공개 요청이 숨김에 막히고 공개 버튼도 등록된 권을 건너뛴다', async () => {
      await register(existing(1));
      assert.deepEqual(await product(1), { is_listed: false, status: 'hidden' });
      assert.deepEqual((await visibility(1, true)).skipped_product_ids, [1]);
      assert.deepEqual(await product(1), { is_listed: true, status: 'sold_out' });
      await visibility(1, false);
    });
    await db.exec(read('20261111093904_fix_register_product_visibility.sql'));

    await t.test('기존 숨김 상품 공개 등록: 신규 권만 공개하고 이전 비공개 권은 보존', async () => {
      const result = await register(existing(1, true, 10950, 2));
      assert.equal(result.published_books, 2);
      assert.equal(result.unpublished_books, 0);
      assert.deepEqual(await product(1), { is_listed: true, status: 'selling' });
      assert.deepEqual((await db.query('select is_public from books where product_id=1 order by id')).rows, [{ is_public: false }, { is_public: true }, { is_public: true }]);
      assert.equal(result.created_serials.length, 2);
    });
    await t.test('공개 안 함·가격 없음·수량 0은 숨김 상품을 자동 공개하지 않는다', async () => {
      assert.equal((await register(existing(2, false))).unpublished_books, 1);
      assert.equal((await register(existing(3, true, null))).unpublished_books, 1);
      assert.equal((await register(existing(3, true, 10000, 0))).created_books, 0);
      for (const id of [2, 3]) assert.deepEqual(await product(id), { is_listed: false, status: 'hidden' });
      assert.equal((await register(existing(1, false))).published_books, 0);
      assert.equal((await product(1)).is_listed, true);
    });
    await t.test('신규 입력의 기존 상품 병합·신상품·비공개 등록·가격 누락을 구분', async () => {
      const result = await register({ new_products: [
        { title: 'matched-new', is_public: true, original_price: 21900, quantity: 2 },
        { title: 'brand-new', is_public: true, original_price: 20000 },
        { title: 'brand-new-hidden', is_public: false, original_price: 20000 },
        { title: 'brand-new-no-price', is_public: true },
      ] });
      assert.equal(result.created_products, 3);
      assert.equal(result.created_books, 5);
      assert.equal(result.published_books, 3);
      assert.equal(result.unpublished_books, 2);
      assert.equal((await product(4)).status, 'selling');
      assert.deepEqual((await db.query("select status from products where title in ('brand-new-hidden','brand-new-no-price')")).rows, [{ status: 'hidden' }, { status: 'hidden' }]);
    });
    await t.test('공개 버튼은 등록과 같은 최소 조건 적용, 가격 누락은 계속 제외', async () => {
      assert.equal((await visibility(2, true)).updated_books, 1);
      assert.equal((await product(2)).status, 'selling');
      assert.deepEqual((await visibility(3, true)).skipped_product_ids, [3]);
    });
    await t.test('일반 재입고·주문 취소는 숨김을 유지하고 관리자 권한도 보존', async () => {
      await visibility(2, false);
      await db.exec("update books set status='reserved' where product_id=2; update books set status='on_sale',is_public=true where product_id=2");
      assert.equal((await product(2)).status, 'hidden');
      await db.exec("set app.test_admin='false'");
      await assert.rejects(register(existing(2)), /Admin access required/);
      await assert.rejects(visibility(2, true), /Admin access required/);
      await db.exec("set app.test_admin='true'");
      assert.equal((await db.query("select has_function_privilege('anon','admin_register_customer_inventory(bigint,jsonb)','execute') as allowed")).rows[0].allowed, false);
    });
    await t.test('중복 채번·상품 공개 제한 실패는 공개 전환과 재고 생성을 함께 롤백', async () => {
      const serial = (await db.query('select serial_number from books order by id limit 1')).rows[0].serial_number;
      await assert.rejects(register({ ...existing(2), serial_start: serial }), /이미 사용 중/);
      assert.equal((await product(2)).is_listed, false);
      await db.exec(`create function test_block_listing() returns trigger language plpgsql as $$begin
        if new.id=5 and new.is_listed then raise exception '판매 제한'; end if; return new; end$$;
        create trigger block_listing before update of is_listed on products for each row execute function test_block_listing();`);
      await assert.rejects(register(existing(5)), /판매 제한/);
      assert.equal((await product(5)).is_listed, false);
      assert.equal((await db.query('select count(*)::int as n from books where product_id=5')).rows[0].n, 0);
    });
  } finally {
    await db.close();
  }
});
